import assert from 'node:assert/strict';
import { createGame, rollDice } from './engine.js';
import { initPresence, setPresence, expirePresence, RECONNECT_MS, HEARTBEAT_GRACE_MS } from './monopolyPresence.js';
const players = [{id:5},{id:9},{id:11}];
const time=1_000_000;
let game=initPresence(createGame({names:['Ali','Bintou','Coco']}),players.map(p=>p.id),time);
assert.deepEqual(game.presence.away,{});
assert.equal(setPresence(game,players,9,'away',time+5_000),true);
assert.equal(game.presence.away['9'],time+5_000);
setPresence(game,players,5,'here',time+RECONNECT_MS-1_000);
setPresence(game,players,11,'here',time+RECONNECT_MS-1_000);
assert.equal(expirePresence(game,players,time+RECONNECT_MS).changed,false);
assert.equal(game.players[1].bankrupt,false);
assert.equal(setPresence(game,players,9,'here',time+60_000),true);
assert.equal(game.presence.away['9'],undefined);
assert.equal(setPresence(game,players,11,'away',time+100_000),true);
setPresence(game,players,5,'here',time+100_000+RECONNECT_MS-1000);
setPresence(game,players,9,'here',time+100_000+RECONNECT_MS-1000);
const active=game.current;
let result=expirePresence(game,players,time+100_000+RECONNECT_MS+1);
assert.equal(result.changed,true);
assert.equal(result.game.players[2].bankrupt,true);
assert.equal(result.game.current,active);
let game2=initPresence(createGame({names:['Ali','Bintou']}),[5,9],time);
game2=rollDice(game2,{forced:[2]});
setPresence(game2,[{id:5},{id:9}],5,'away',time+10_000);
setPresence(game2,[{id:5},{id:9}],9,'here',time+10_000+RECONNECT_MS-1000);
result=expirePresence(game2,[{id:5},{id:9}],time+10_000+RECONNECT_MS);
assert.equal(result.game.phase,'over');assert.equal(result.game.winner,1);
let game3=initPresence(createGame({names:['Ali','Bintou']}),[5,9],time);
result=expirePresence(game3,[{id:5},{id:9}],time+HEARTBEAT_GRACE_MS+1);
assert.equal(result.game.presence.away['5'],time+HEARTBEAT_GRACE_MS);
let allGone=initPresence(createGame({names:['A','B']}),[5,9],time);
setPresence(allGone,[{id:5},{id:9}],5,'away',time+50_000);
setPresence(allGone,[{id:5},{id:9}],9,'away',time+51_000);
let cancelled=expirePresence(allGone,[{id:5},{id:9}],time+50_000+RECONNECT_MS);
assert.equal(cancelled.game.phase,'over');assert.equal(cancelled.game.winner,-1);
console.log('OK - absences 2 min, retour, expiration, absence collective et detection deconnexion.');
